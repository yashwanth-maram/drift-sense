#!/usr/bin/env python3
"""Can we predict failure before it happens?

Across 100 samples generated by the reference generator, every failing
axis had its true coordinate inside a mat interior -- 24 out of 24. A
mat-interior crop is a pure periodic lattice, and the mat boundary that
would fix which period you are on lies outside the crop. Every observed
error was an integer number of lattice periods.

That condition is detectable at inference from the template alone: does
the template contain a peripheral strip on this axis? If it does, the
axis is pinned. If it does not, the axis is at risk.

This script measures whether that holds, per axis, and what it is worth
as a confidence score. For a real inspection tool an admitted failure is
far more useful than a confident wrong answer -- the tool can re-acquire.
Applied Materials' own evaluation harness scores average precision, which
is exactly the ability to reject your own bad answers.

    python experiments/predict_risk.py --data ../am_eval --n 100
"""

from __future__ import annotations

import argparse
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np
import cv2

from driftsense.localize import localize, _strip_centres

TOL = 5.0


def load_manifest(data_dir):
    for root, _, files in os.walk(data_dir):
        if "manifest.csv" in files:
            with open(os.path.join(root, "manifest.csv")) as fh:
                return list(csv.DictReader(fh)), root
    raise SystemExit(f"no manifest.csv under {data_dir}")


def confusion(pred_risky, actually_wrong, label):
    pred_risky = np.asarray(pred_risky, bool)
    actually_wrong = np.asarray(actually_wrong, bool)
    tp = int((pred_risky & actually_wrong).sum())
    fp = int((pred_risky & ~actually_wrong).sum())
    fn = int((~pred_risky & actually_wrong).sum())
    tn = int((~pred_risky & ~actually_wrong).sum())

    print(f"\n  {label}")
    print(f"    {'':16}{'actually wrong':>16}{'actually right':>16}")
    print(f"    {'flagged risky':16}{tp:>16}{fp:>16}")
    print(f"    {'flagged safe':16}{fn:>16}{tn:>16}")

    if tp + fn:
        print(f"    recall  (failures caught) : {tp / (tp + fn) * 100:5.1f}%")
    if tn + fp:
        print(f"    accuracy when flagged safe: {tn / (tn + fp) * 100:5.1f}%"
              f"   ({tn}/{tn + fp})")
    if tp + fp:
        print(f"    accuracy when flagged risky: {tp / (tp + fp) * 100:5.1f}%"
              f"   failure rate among flagged")
    return tp, fp, fn, tn


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", required=True)
    ap.add_argument("--n", type=int, default=100)
    ap.add_argument("--rung", type=int, default=1)
    ap.add_argument("--tol", type=float, default=TOL)
    a = ap.parse_args(argv)

    _rows, root = load_manifest(a.data)
    rows = _rows[:a.n]

    x_risky, y_risky = [], []
    x_wrong, y_wrong = [], []
    both_ok, errs = [], []
    period_multiples = []

    for row in rows:
        rp, sp = row["reference_path"], row["search_path"]
        if not os.path.exists(rp):
            rp = os.path.join(root, "reference", f"{int(row['id']):05d}.png")
            sp = os.path.join(root, "search", f"{int(row['id']):05d}.png")
        ref = cv2.imread(rp, cv2.IMREAD_GRAYSCALE)
        srch = cv2.imread(sp, cv2.IMREAD_GRAYSCALE)
        if ref is None or srch is None:
            continue

        tmpl = cv2.resize(ref, (100, 100), interpolation=cv2.INTER_AREA)
        # a VERTICAL strip in the template pins the x axis, a HORIZONTAL
        # strip pins y
        has_v = len(_strip_centres(tmpl, 1, 0.45, 6)) > 0
        has_h = len(_strip_centres(tmpl, 0, 0.45, 6)) > 0

        gx, gy = float(row["gt_x"]), float(row["gt_y"])
        r = localize(ref, srch, rung=a.rung)
        dx, dy = abs(r.x - gx), abs(r.y - gy)
        err = float(np.hypot(r.x - gx, r.y - gy))

        x_risky.append(not has_v)
        y_risky.append(not has_h)
        x_wrong.append(dx > a.tol)
        y_wrong.append(dy > a.tol)
        both_ok.append(err <= a.tol)
        errs.append(err)

        if err > a.tol:
            period_multiples.append((int(row["id"]), dx, dy))

    n = len(errs)
    errs = np.asarray(errs)
    print("=" * 66)
    print(f"RISK PREDICTOR   n={n}   rung={a.rung}   tolerance={a.tol:.0f} px")
    print("=" * 66)
    print(f"\n  overall accuracy : {np.mean(errs <= a.tol) * 100:5.1f}%")
    print(f"  median error     : {np.median(errs):5.2f} px")

    confusion(x_risky, x_wrong, "X AXIS  (risky = no vertical strip in template)")
    confusion(y_risky, y_wrong, "Y AXIS  (risky = no horizontal strip in template)")

    # what a confidence gate would buy
    xr = np.asarray(x_risky)
    yr = np.asarray(y_risky)
    ok = np.asarray(both_ok)
    safe = ~xr & ~yr
    partial = (~xr & yr) | (xr & ~yr)
    unsafe = xr & yr

    print("\n" + "=" * 66)
    print("WHAT A CONFIDENCE GATE BUYS")
    print("=" * 66)
    for name, sel in (("both axes pinned", safe),
                      ("one axis pinned", partial),
                      ("neither pinned", unsafe)):
        if sel.sum():
            print(f"  {name:<20} {sel.sum():>4} samples "
                  f"({sel.sum() / n * 100:4.1f}%)   "
                  f"accuracy {ok[sel].mean() * 100:5.1f}%")
        else:
            print(f"  {name:<20}    0 samples")

    if safe.sum():
        print(f"\n  Reporting only fully-pinned predictions would cover "
              f"{safe.sum() / n * 100:.0f}% of cases")
        print(f"  at {ok[safe].mean() * 100:.1f}% precision, versus "
              f"{ok.mean() * 100:.1f}% if everything is reported.")

    print("\n" + "=" * 66)
    print("FAILURE ERRORS  (expect integer multiples of the lattice period)")
    print("=" * 66)
    print(f"  {'id':>4} {'dx':>9} {'dy':>9}")
    for i, dx, dy in period_multiples[:25]:
        print(f"  {i:>4} {dx:>9.2f} {dy:>9.2f}")
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
